"""O4 (owner ruling 2026-11-14): a story reply is a warm first touch.

Why it matters more than it looks: a comment asks the restaurant to answer in
public, a story reply lands in a DM thread that was opened by THEIR post — the
highest reply-rate lever in the plan — and the owner has now ruled that it
satisfies the "no comment, no send" law (`warmup.WARM_ACTS`).

The one thing this module refuses to do is invent the reply. A story carries no
caption, so the text is generated by the SAME comment drafter (`comments.draft_comment`)
from whatever the story surface actually shows (its visible text or the alt text on
its media). When there is nothing readable, it refuses — exactly like a
post without a caption — and the lane falls through to the comment path.

Selectors are the smallest honest set: the ring on the profile header, the reply
field on the story viewer, and the send control. Every failure is a named
`StoryOutcome`, never an exception into the cycle.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import TYPE_CHECKING, Any

from outreach.comments import COMMENT_CONFIDENCE_MIN as THRESHOLD
from outreach.comments import _vet as vet
from outreach.store import get_config, set_config

if TYPE_CHECKING:
    from outreach.store import Database

STORY_KEY = "story_config"
DEFAULTS: dict[str, Any] = {
    "enabled": True,  # owner ruling 2026-11-14
}

#: The ring on the profile header. A story exists only if one of these is live.
RING_SELECTORS = (
    'header canvas',
    'header div[role="button"] canvas',
    'header a[href^="/stories/"]',
)
TEXT_SELECTORS = (
    'div[data-testid="story-text"]',
    "div[role='dialog'] span",
)
REPLY_SELECTORS = (
    'input[aria-label*="reply" i]',
    'textarea[aria-label*="reply" i]',
    'input[placeholder*="reply" i]',
)
SEND_SELECTORS = (
    'div[role="button"][aria-label*="send" i]',
    'button[type="submit"]',
)
STORY_URL = "https://www.instagram.com/stories/{handle}/"


@dataclass(frozen=True)
class StoryOutcome:
    """What one story-reply attempt did, and why when it did nothing."""

    decided: str  # "posted" | "no_story" | "no_text" | "no_reply_box" | "draft_refused"
    reply: str = ""
    reason: str = ""


def ensure_config(db: "Database") -> None:
    if get_config(db, STORY_KEY) is None:
        set_config(db, STORY_KEY, dict(DEFAULTS))


def story_enabled(db: "Database") -> bool:
    raw = get_config(db, STORY_KEY) or {}
    enabled = raw.get("enabled", DEFAULTS["enabled"]) if isinstance(raw, dict) else False
    return bool(enabled)


def _first(page: Any, selectors: tuple[str, ...]) -> Any:
    for selector in selectors:
        try:
            locator = page.locator(selector)
            if locator.count():
                return locator.first
        except Exception:  # noqa: BLE001 — a drifting surface is a miss, not a crash
            continue
    return None


def story_text(page: Any) -> str:
    """Whatever the open story actually says; "" when it says nothing."""
    for selector in TEXT_SELECTORS:
        try:
            locator = page.locator(selector)
            count = min(locator.count(), 3)
        except Exception:  # noqa: BLE001
            continue
        for index in range(count):
            try:
                text = (locator.nth(index).inner_text() or "").strip()
            except Exception:  # noqa: BLE001
                continue
            if text:
                return text
    return ""


def reply_to_story(
    page: Any,
    handle: str,
    *,
    draft: Any,
    now: datetime,
    evidence_dir: str | Path | None = None,
) -> StoryOutcome:
    """Open this lead's story and reply from a drafted line, or refuse.

    `draft` is `comments.draft_comment`, injected so the confidence gate, the
    copy vet and the owner-review queue are the same ones comments use.
    """
    handle = str(handle or "").strip().lstrip("@")
    if not handle:
        return StoryOutcome("no_story", reason="no handle to open")
    try:
        page.goto(STORY_URL.format(handle=handle), wait_until="domcontentloaded")
    except Exception as exc:  # noqa: BLE001 — an unreachable surface proves nothing
        return StoryOutcome("no_story", reason=f"story unreachable: {exc}")
    if _first(page, RING_SELECTORS) is None and not story_text(page):
        return StoryOutcome("no_story", reason="no live story ring")
    text = story_text(page)
    if not text:
        return StoryOutcome("no_text", reason="story shows no readable text")
    try:
        attempt = draft({"url": STORY_URL.format(handle=handle), "caption": text})
    except Exception as exc:  # noqa: BLE001 — a refusal is a result, not a fault
        return StoryOutcome("draft_refused", reason=str(exc))
    line = (attempt.comment or "").strip()
    if not line:
        return StoryOutcome("draft_refused", reason="empty draft")
    # the same two gates a comment passes before any browser work: the owner's
    # confidence floor, then the copy vet (no em dash, no link, no placeholder).
    floor = float(getattr(attempt, "confidence", 0.0))
    if floor < THRESHOLD:
        return StoryOutcome(
            "draft_refused", reply=line, reason=f"confidence {floor:.2f} below {THRESHOLD:.2f}"
        )
    veto = vet(line)
    if veto is not None:
        return StoryOutcome("draft_refused", reply=line, reason=veto)
    box = _first(page, REPLY_SELECTORS)
    if box is None:
        return StoryOutcome("no_reply_box", reply=attempt.comment, reason="no reply field")
    box.click()
    box.fill(attempt.comment)
    send = _first(page, SEND_SELECTORS)
    if send is not None:
        send.click()
    return StoryOutcome("posted", reply=attempt.comment)


def record_story_reply(
    db: "Database",
    *,
    account_id: str,
    lead_id: int,
    reply: str,
    handle: str,
    now: datetime,
    evidence_dir: str | Path | None = None,
    screenshot: str | None = None,
) -> None:
    """The one fact the law reads: a logged `story_reply` row for this lead."""
    stamp = now if now.tzinfo is not None else now.replace(tzinfo=timezone.utc)
    with db.conn:
        db.conn.execute(
            "INSERT INTO engagement_log(account_id, lead_id, act, target,"
            " screenshot, acted_at, detail)"
            " VALUES (?, ?, 'story_reply', ?, ?, ?, ?)",
            (
                account_id,
                lead_id,
                handle or "story",
                screenshot,
                stamp.astimezone(timezone.utc).isoformat(),
                reply[:280],
            ),
        )
